/** ① 매일 아침 — 전날(KST) 뉴스·자료 검색 + 분석 */
export function dailyPrompt(
  runDateHuman: string,
  newsDateHuman: string,
  newsDateIso: string,
  knownItemsSummary: string
): string {
  return `오늘 ${runDateHuman} 아침이다. **${newsDateHuman} (${newsDateIso}, KST 하루)** 동안 나온 뉴스·자료만 웹 검색으로 수집하고 분석해줘.
다른 날짜 소식은 포함하지 마.

## 이미 수집한 자료 (중복 금지)
아래 URL·헤드라인과 **같은 소식·같은 기사**는 절대 다시 넣지 마.
${knownItemsSummary}

## 조사 범위 (5개 축 — 축별 0~5건, 해당 없으면 "- 해당 없음")
- **축당 1건만 고르지 말 것.** 관련 뉴스가 여러 건이면 **기사마다 ### 블록**을 따로 작성
- 중요도 순, 확인된 소식은 빠짐없이 (최대 5건/축)
- 하루 전체 **총 15~25건** 목표
${AXES}

## 출력 형식 (마크다운 — 아래 예시를 **정확히** 따를 것)

### 금지
- \`## ${newsDateIso} 일일 리서치\` 같은 날짜 제목 **쓰지 말 것**
- 한 줄에 요약+분석+출처 **몰아넣지 말 것**
- \`**[헤드라인]** — ...\` 불릿 형식 **쓰지 말 것**
- "## 참고 출처" 섹션 **금지**

### 필수 구조
1. 축마다 \`## 축 이름\` 헤딩
2. 기사마다 \`### 헤드라인\` (대괄호·볼드 없이 plain text)
3. **반드시 아래 3줄을 각각 별도 줄**로 (순서 고정, \`**요약** ·\` / \`**분석** ·\` / \`**출처** ·\` 접두어 사용):
   - **요약** · 무슨 일인지 1~2문장 (짧게)
   - **분석** · 왜 중요한지 1~2문장 (짧게)
   - **출처** · [매체명](URL)

### 출력 예시
${DAILY_FORMAT_EXAMPLE}

- 해당 축에 신규 없으면: \`- 해당 없음\` 한 줄만
- 전체 신규 없으면: \`## 요약\` 아래 \`- 신규 항목 없음\`
${LINK_RULE}
- 다른 인사말 없이 본문만 출력`;
}

/** ② 월요일 아침 — 월~일 일일 리서치 원문 기반 주간 인사이트 */
export function weeklyInsightPrompt(
  runDateHuman: string,
  weekId: string,
  newsDates: string[],
  dailyLogs: { iso: string; content: string }[]
): string {
  const corpus = dailyLogs
    .map((d) => `### ${d.iso} 일일 리서치\n${d.content}`)
    .join('\n\n');

  const missing = newsDates.filter((d) => !dailyLogs.some((l) => l.iso === d));

  return `오늘 ${runDateHuman} 월요일 아침이다. 아래는 ${weekId} 주차 **월~일(${newsDates.join(', ')})** 일일 리서치 원문이다.
이 원문만 근거로 **팀 공유용 주간 인사이트**를 작성해줘. **새로운 웹 검색·외부 지식 추가 금지.**

${missing.length > 0 ? `⚠️ 수집본 없는 날짜: ${missing.join(', ')} (해당 날짜 언급 금지)\n` : ''}
---
${corpus || '(수집본 없음)'}
---

## 0단계 — **통합·선별** (출력 전 내부 정리)
일일 리서치 전체를 훑고 **중요한 것만** 골라 통합:

**주요 이슈 선정 우선순위 (높은 순):**
1. **팀 프로덕트 직접 연관** — Vault / RWA 담보대출 / RWA 상품발행 / STO와 밀접
2. **다수 매체·반복 보도** — 여러 날·여러 출처에서 다룬 소식
3. **파급효과·업계 주목** — 규제·대형 기관·인프라 변화 등 파급 큰 이슈

**통합 규칙:**
- 같은 규제·기관·회사·주제 → 1개 이슈로 묶기
- 통합 이슈는 출처 1~3개를 한 블록에

**분량 상한:**
| 섹션 | 최대 |
|------|------|
| 주요 이슈 | **4~6개** (선별·통합 후) |
| 해석 · 관점 | **2~3개** 테마 |
| 다음 주 전망 | **2~3개** (짧게) |
| 담당 프로덕트 | **관련 있는 라인만** (0~4개) |

## 섹션별 역할
| 섹션 | 답하는 질문 |
|------|------------|
| 주요 이슈 | 무슨 일이 있었나 + **왜 이번 주 핵심인가** |
| 해석 · 관점 | 여러 이슈를 **한 문장으로 관통하는** 흐름·의미 |
| 다음 주 전망 | **짧게** 무엇을 볼까 |
| 담당 프로덕트 | **우리 4개 라인**에 실질적 시사 (있을 때만) |

- 같은 ### 제목을 여러 섹션에 쓰지 말 것
- 한 줄에 여러 필드 몰아넣지 말 것

## 작성 규칙
- 일일 리서치 **사실만** 사용, 근거 링크 [매체명](URL) 필수

## 출력 형식

### ## 이번 주 한 줄 요약
- 2~3문장. 이번 주 **큰 그림**만

### ## 주요 이슈 (4~6개, 선별·통합)
> ### = **통합 주제명**. **사실**과 **왜 주목**은 **반드시 분리** (아래 형식). 한 줄에 "사실 · ..." 형태 **금지**.

### (통합 주제명)
**사실**
(2~3문장 — **다음 줄**부터 본문. 라벨과 내용 분리)

**왜 주목**
(1~2문장 — **별도 블록**. 팀 연관 / 다수 매체·반복 보도 / 파급·업계 주목 중 해당)

**출처** · [매체1](URL), [매체2](URL)

### ## 해석 · 관점 (2~3개 테마)
> ### = **횡단 테마명** (뉴스 헤드라인 X). **관찰+시사를 한 필드**로 통합 — 나누지 말 것.

### (테마명)
**해석** · 이번 주 흐름·패턴·업계 의미를 **2~3문장**으로 (관찰과 시사를 구분하지 말고 하나로)
**근거** · [매체](URL) (1~2개)

### ## 다음 주 전망 · 주시 포인트 (2~3개)
> 항목당 **주시** 1~2문장 + 근거. 세부 일정·수치 금지.

### (짧은 제목)
**주시** · 1~2문장
**근거** · [매체](URL)

### ## 담당 프로덕트 시사점
${PRODUCT_LINES}

- **실질 연관 있는 라인만** ### 작성 (0~4개). 억지로 채우지 말 것
- ### 제목: **Vault** / **RWA 담보대출** / **RWA 상품발행** / **STO** (정확히)
- **기술 / 규제 / 비즈니스** 중 **해당하는 관점만** 작성 (최소 1개 + **근거**). 해당 없는 관점은 **줄 자체를 쓰지 말 것**

### Vault
**기술** · 온체인 구조·프로토콜·인프라·UX 관점 (해당 시 1~2문장)
**규제** · 컴플라이언스·인허가·감독 관점 (해당 시 1~2문장)
**비즈니스** · 시장·수익·경쟁·Go-to-market 관점 (해당 시 1~2문장)
**근거** · [매체](URL)

(다른 프로덕트 라인도 동일 — 관련 관점만, **시사** 한 줄 대신 위 3관점 활용)

- "## ${weekId} 주간 인사이트" / "## 참고 출처" **금지**
- 다른 인사말 없이 본문만 출력`;
}

export function monthlyPrompt(todayKst: string): string {
  return `오늘은 ${todayKst}이다. 이번 달 발행된 토큰화 관련 기관 보고서(BIS, IMF, JPM, DTCC, 대형 운용사, CoinGecko/RedStone/Gauntlet 리서치 등)를 웹 검색으로 찾아줘.

## 출력 형식 (마크다운)
- "## 이번 달 보고서 목록": 보고서마다 ### 제목 + **발행처** · / **출처** · [링크](URL)
- "## 딥다이브": ### 보고서명 + **핵심 주장** · (5개, 각각 별도 ### 또는 불릿) + **시사점** · (3개)
${LINK_RULE}
- 다른 인사말 없이 본문만 출력`;
}
