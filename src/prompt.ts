export function weeklyVerifyPrompt(
  runStamp: string,
  weekId: string,
  draft: string,
  dailyLogs: { iso: string; content: string }[]
): string {
  const corpus = dailyLogs
    .map((d) => `### ${d.iso} 일일 리서치\n${d.content}`)
    .join('\n\n');

  return `지금은 ${runStamp}이다. ${weekId} 주간 인사이트 **초안을 웹 검색으로 검증**하고, 같은 출력 형식으로 최종본을 내.

## 할 일
1. 이슈·시그널의 **수치, 날짜, 당사자, 규제·상품 상태**를 검색해 확인
2. 맞으면 **교차검증**에 확인 매체·합의/이견을 구체화하고 **신뢰도**를 높음/중간/낮음으로 확정
3. 틀리면 사실을 고치고, 고친 이유를 교차검증에 한 줄
4. 확인 불가·단일 저품질 출처는 본문에서 빼거나 ## 미확인 · 주의 로 이동
5. **일일 리서치에 없는 새 이슈를 추가하지 말 것.** 기존 이슈의 팩트 보강만
6. 공식 원문(규제기관·회사 IR·블로그)이 있으면 출처에 추가
7. **업데이트** 줄은 \`${runStamp}\` 로 유지

## 초안
---
${draft}
---

## 일일 리서치 (범위 가드 — 여기서 벗어난 새 이야기 금지)
---
${corpus || '(없음)'}
---

출력은 초안과 **동일한 섹션·필드 형식**(브리프 / 시그널 / 이슈 / 이번 주 흐름 / 시나리오 / 프로덕트 / 미확인).
인사말 없이 최종 마크다운만.`;
}

